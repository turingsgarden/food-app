// MARK: - Main DietPlanView

struct DietPlanView: View {
    @EnvironmentObject var themeManager: ThemeManager
    @ObservedObject var session = SessionManager.shared
    @State private var healthProfile: HealthProfile?
    @State private var healthReport: HealthReport?
    @State private var isLoading = false
    @State private var isGenerating = false
    @State private var errorMsg = ""
    @State private var showError = false
    @State private var showProfileSetup = false
    @State private var showRefreshPrompt = false
    @State private var viewMode: ReportViewMode = .scroll
    @State private var pagedIndex: Int = 0
    @State private var showShareSheet = false
    @State private var shareItems: [Any] = []

    var currentUserId: String { session.userID.isEmpty ? UserDefaults.standard.string(forKey:"user_id") ?? "" : session.userID }

    var body: some View {
        NavigationStack {
            ZStack {
                themeManager.current.background.ignoresSafeArea()
                if isLoading { loadingView }
                else if isGenerating { generatingView }
                else if healthProfile == nil { noProfileView }
                else if let report = healthReport {
                    if viewMode == .scroll { scrollReport(report: report) }
                    else { pagedReport(report: report) }
                }
                else { generatePromptView }
            }
            .preferredColorScheme(themeManager.current.colorScheme)
            .navigationBarHidden(true)
            .onAppear { loadData() }
            .alert("Error", isPresented: $showError) { Button("OK", role: .cancel) {} } message: { Text(errorMsg) }
            .sheet(isPresented: $showProfileSetup) {
                HealthProfileView { profile in
                    self.healthProfile = profile
                    HealthAPIManager.shared.saveHealthProfile(profile) { _,_ in }
                    generateReport(force: true)
                }.environmentObject(themeManager)
            }
            .sheet(isPresented: $showShareSheet) { ShareSheet(items: shareItems) }
            .alert("Update Your Health Plan?", isPresented: $showRefreshPrompt) {
                Button("Yes, Regenerate") { generateReport(force: true) }
                Button("Keep Current Plan", role: .cancel) {}
            } message: { Text("It's been over 7 days since your last report. Refresh with your latest profile?") }
        }
    }

    // MARK: - Data

    func loadData() {
        guard healthReport == nil, !isLoading, !isGenerating else { return }
        isLoading = true
        HealthAPIManager.shared.fetchHealthProfile(userId: currentUserId) { profile in
            self.healthProfile = profile
            guard profile != nil else { self.isLoading = false; return }
            HealthAPIManager.shared.fetchHealthReport { report in
                self.isLoading = false
                if let r = report { self.healthReport = r; self.checkReportAge(report: r) }
                else { self.generateReport(force: false) }
            }
        }
    }

    func checkReportAge(report: HealthReport) {
        guard let str = report.createdAt else { return }
        let f1 = ISO8601DateFormatter(); f1.formatOptions = [.withInternetDateTime,.withFractionalSeconds]
        let f2 = ISO8601DateFormatter(); f2.formatOptions = [.withInternetDateTime]
        guard let date = f1.date(from: str) ?? f2.date(from: str) else { return }
        let days = Calendar.current.dateComponents([.day], from: date, to: Date()).day ?? 0
        if days >= 7 { DispatchQueue.main.asyncAfter(deadline: .now()+0.5) { self.showRefreshPrompt = true } }
    }

    func generateReport(force: Bool) {
        isGenerating = true
        HealthAPIManager.shared.generateHealthReport(goals: [], force: force) { report, err in
            self.isGenerating = false
            if let r = report { self.healthReport = r }
            else { self.errorMsg = err ?? "Failed to generate report"; self.showError = true }
        }
    }

    // MARK: - Top Bar

    func topBar(report: HealthReport) -> some View {
        HStack(alignment: .top) {
            VStack(alignment: .leading, spacing: 3) {
                Text("Health Report").font(.system(size: 26, weight: .black, design: .rounded)).foregroundColor(themeManager.current.primaryText)
                if let date = report.createdAt {
                    Text("Updated \(formatDate(date))").font(.system(size: 12)).foregroundColor(themeManager.current.secondaryText)
                }
            }
            Spacer()
            HStack(spacing: 10) {
                Button(action: { showProfileSetup = true }) {
                    HStack(spacing: 5) {
                        Image(systemName: "pencil").font(.system(size: 11, weight: .semibold))
                        Text("Edit").font(.system(size: 12, weight: .semibold))
                    }
                    .foregroundColor(themeManager.current == .dark ? .black : .white)
                    .padding(.horizontal, 10).padding(.vertical, 7)
                    .background(themeManager.current == .dark ? Color.white : Color.black).cornerRadius(20)
                }
                Menu {
                    Section("View") {
                        ForEach(ReportViewMode.allCases, id: \.self) { mode in
                            Button(action: { withAnimation(.spring(response:0.35,dampingFraction:0.8)) { viewMode = mode; pagedIndex = 0 } }) {
                                Label(viewMode == mode ? "\(mode.rawValue) ✓" : mode.rawValue, systemImage: mode.icon)
                            }
                        }
                    }
                    Divider()
                    Button(action: { shareItems = [buildReportText(report)]; showShareSheet = true }) {
                        Label("Share Report", systemImage: "square.and.arrow.up")
                    }
                    Button(action: { UIPasteboard.general.string = buildReportText(report) }) {
                        Label("Copy as Text", systemImage: "doc.on.doc")
                    }
                    Divider()
                    Button(action: { generateReport(force: true) }) {
                        Label("Regenerate Report", systemImage: "arrow.clockwise")
                    }
                } label: {
                    Image(systemName: "ellipsis.circle").font(.system(size: 20, weight: .medium))
                        .foregroundColor(themeManager.current.primaryText)
                        .frame(width: 36, height: 36).background(themeManager.current.inputBackground).cornerRadius(10)
                }
            }
        }
        .padding(.horizontal, 20).padding(.top, 20).padding(.bottom, 16)
    }

    // MARK: - Scroll Mode

    func scrollReport(report: HealthReport) -> some View {
        ScrollView(showsIndicators: false) {
            VStack(spacing: 0) {
                topBar(report: report)
                AIWaveformStrip(report: report).environmentObject(themeManager).padding(.horizontal,20).padding(.bottom,16)
                scoreHeroCard(report: report).padding(.horizontal,20).padding(.bottom,16)
                profileCompletenessCard(report: report).padding(.horizontal,20).padding(.bottom,16)
                nutritionGoalsCard(report: report).padding(.horizontal,20).padding(.bottom,16)
                if !report.attentionItems.isEmpty { healthIndicatorsSection(items: report.attentionItems).padding(.horizontal,20).padding(.bottom,16) }
                if !report.recommendedFoods.isEmpty { recommendedFoodsSection(foods: report.recommendedFoods).padding(.bottom,16) }
                if !report.foodsToLimit.isEmpty { foodsToLimitCard(foods: report.foodsToLimit).padding(.horizontal,20).padding(.bottom,16) }
                lifestyleTipCard(tip: report.lifestyleTip).padding(.horizontal,20).padding(.bottom,100)
            }
        }
    }

    // MARK: - Paged Mode

    func pagedReport(report: HealthReport) -> some View {
        var pages: [(String, AnyView)] = [
            ("Overview",        AnyView(VStack(spacing:16){ AIWaveformStrip(report:report).environmentObject(themeManager); scoreHeroCard(report:report); profileCompletenessCard(report:report) }.padding(.horizontal,20))),
            ("Nutrition Goals", AnyView(nutritionGoalsCard(report:report).padding(.horizontal,20))),
        ]
        if !report.attentionItems.isEmpty { pages.append(("Health Indicators", AnyView(healthIndicatorsSection(items:report.attentionItems).padding(.horizontal,20)))) }
        if !report.recommendedFoods.isEmpty { pages.append(("Recommended Foods", AnyView(recommendedFoodsSection(foods:report.recommendedFoods)))) }
        if !report.foodsToLimit.isEmpty || !report.lifestyleTip.isEmpty {
            pages.append(("Foods & Tip", AnyView(VStack(spacing:16){ if !report.foodsToLimit.isEmpty { foodsToLimitCard(foods:report.foodsToLimit).padding(.horizontal,20) }; lifestyleTipCard(tip:report.lifestyleTip).padding(.horizontal,20) })))
        }

        return VStack(spacing: 0) {
            topBar(report: report)
            // Dots + page counter
            HStack(spacing: 6) {
                ForEach(0..<pages.count, id: \.self) { i in
                    Capsule()
                        .fill(i == pagedIndex ? (themeManager.current == .dark ? Color.white : Color.black) : themeManager.current.cardBorder)
                        .frame(width: i == pagedIndex ? 20 : 6, height: 6)
                        .animation(.spring(response:0.3,dampingFraction:0.7), value: pagedIndex)
                }
                Spacer()
                Text("\(pagedIndex+1) / \(pages.count)").font(.system(size:12)).foregroundColor(themeManager.current.secondaryText)
            }
            .padding(.horizontal,20).padding(.bottom,12)

            TabView(selection: $pagedIndex) {
                ForEach(Array(pages.enumerated()), id: \.0) { idx, page in
                    ScrollView(showsIndicators: false) {
                        VStack(alignment: .leading, spacing: 0) {
                            Text(page.0).font(.system(size:13,weight:.semibold)).foregroundColor(themeManager.current.secondaryText)
                                .textCase(.uppercase).tracking(0.5).padding(.horizontal,20).padding(.bottom,14)
                            page.1
                            Spacer(minLength: 80)
                        }.padding(.top,4)
                    }.tag(idx)
                }
            }
            .tabViewStyle(.page(indexDisplayMode: .never))
        }
    }

    // MARK: - Cards

