        let color = scoreColor(report.healthScore)
        return HStack(spacing:20) {
            ZStack {
                Circle().stroke(color.opacity(0.12),lineWidth:12).frame(width:110,height:110)
                Circle().trim(from:0,to:CGFloat(report.healthScore)/100.0)
                    .stroke(color,style:StrokeStyle(lineWidth:12,lineCap:.round))
                    .frame(width:110,height:110).rotationEffect(.degrees(-90))
                    .animation(.easeOut(duration:1.2),value:report.healthScore)
                VStack(spacing:1) {
                    Text("\(report.healthScore)").font(.system(size:32,weight:.black,design:.rounded)).foregroundColor(themeManager.current.primaryText)
                    Text("/ 100").font(.system(size:11,weight:.medium)).foregroundColor(themeManager.current.secondaryText)
                }
            }
            VStack(alignment:.leading,spacing:10) {
                Text(report.statusBadge).font(.system(size:12,weight:.bold)).foregroundColor(color)
                    .padding(.horizontal,10).padding(.vertical,4).background(color.opacity(0.10)).cornerRadius(20)
                    .overlay(RoundedRectangle(cornerRadius:20).stroke(color.opacity(0.25),lineWidth:1))
                Text(report.healthSummary).font(.system(size:13)).lineSpacing(3).foregroundColor(themeManager.current.secondaryText).fixedSize(horizontal:false,vertical:true)
            }.frame(maxWidth:.infinity,alignment:.leading)
        }
        .padding(20).background(themeManager.current.cardBackground).cornerRadius(20)
        .overlay(RoundedRectangle(cornerRadius:20).stroke(color.opacity(0.15),lineWidth:1.5))
    }

    func scoreColor(_ s: Int) -> Color { s>=80 ? .green : s>=60 ? .orange : .red }

    func profileCompletenessCard(report: HealthReport) -> some View {
        let filled = min(report.attentionItems.filter { i in ["blood pressure","bp","sugar","glucose","cholesterol","triglycerides"].contains{i.metric.lowercased().contains($0)} }.count,4)
        let pct = Double(filled)/4.0; let done = filled==4
        return Button(action:{showProfileSetup=true}) {
            HStack(spacing:14) {
                ZStack {
                    Circle().stroke(themeManager.current.cardBorder,lineWidth:5).frame(width:44,height:44)
                    Circle().trim(from:0,to:pct).stroke(done ? Color.green : Color.orange,style:StrokeStyle(lineWidth:5,lineCap:.round))
                        .frame(width:44,height:44).rotationEffect(.degrees(-90))
                    Text("\(filled)/4").font(.system(size:11,weight:.bold,design:.rounded)).foregroundColor(themeManager.current.primaryText)
                }
                VStack(alignment:.leading,spacing:3) {
                    Text(done ? "Profile complete" : "Add more data for a better report").font(.system(size:14,weight:.semibold)).foregroundColor(themeManager.current.primaryText)
                    Text(done ? "All clinical markers filled — fully personalised" : "Blood pressure, glucose, cholesterol & triglycerides improve accuracy")
                        .font(.system(size:12)).foregroundColor(themeManager.current.secondaryText).fixedSize(horizontal:false,vertical:true)
                }
                Spacer()
                if !done { Image(systemName:"chevron.right").font(.system(size:12)).foregroundColor(themeManager.current.secondaryText.opacity(0.5)) }
            }
            .padding(14).background(done ? Color.green.opacity(0.04) : Color.orange.opacity(0.04)).cornerRadius(16)
            .overlay(RoundedRectangle(cornerRadius:16).stroke(done ? Color.green.opacity(0.15) : Color.orange.opacity(0.20),lineWidth:1))
        }.buttonStyle(.plain)
    }

