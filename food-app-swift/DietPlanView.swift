// MARK: - View Mode

enum ReportViewMode: String, CaseIterable {
    case scroll = "Scroll"
    case paged  = "Paged"
    var icon: String { self == .scroll ? "rectangle.arrowtriangle.2.outward" : "rectangle.on.rectangle" }
}

// MARK: - Share Sheet


func buildReportText(_ report: HealthReport) -> String {
    var lines = ["NutriCam Health Report",
                 "Health Score: \(report.healthScore)/100 — \(report.statusBadge)", "",
                 report.healthSummary, "",
                 "Daily Nutrition Goals",
                 "Calories: \(report.dailyCalories) kcal",
                 "Protein: \(report.proteinG)g  |  Carbs: \(report.carbsG)g  |  Fat: \(report.fatG)g",
                 "Fiber: \(report.fiberG)g  |  Sodium: \(report.sodiumMg)mg",
                 "Weekly total: \(report.weeklyCalories) kcal"]
    if !report.attentionItems.isEmpty {
        lines += ["", "Health Indicators"]
        lines += report.attentionItems.map { "• \($0.metric): \($0.currentValue) — \($0.advice)" }
    }
    if !report.recommendedFoods.isEmpty {
        lines += ["", "Recommended Foods"]
        lines += report.recommendedFoods.map { "• \($0.food): \($0.reason)" }
    }
    if !report.foodsToLimit.isEmpty {
        lines += ["", "Foods to Limit", report.foodsToLimit.joined(separator: ", ")]
    }
    lines += ["", "Tip: \(report.lifestyleTip)", "", "Generated by NutriCam AI"]
    return lines.joined(separator: "\n")
}

// MARK: - AI Waveform Strip

struct AIWaveformStrip: View {
    @EnvironmentObject var themeManager: ThemeManager
    let report: HealthReport
    var hasBP: Bool      { report.attentionItems.contains { $0.metric.lowercased().contains("blood pressure") || $0.metric.lowercased().contains("bp") } }
    var hasGlucose: Bool { report.attentionItems.contains { $0.metric.lowercased().contains("sugar") || $0.metric.lowercased().contains("glucose") } }
    var bmiDetail: String {
        report.attentionItems.first { $0.metric.lowercased().contains("bmi") }.map { "\($0.currentValue) · \($0.status.capitalized)" } ?? "Analysed"
    }
    var body: some View {
        VStack(alignment: .leading, spacing: 12) {
            HStack(spacing: 10) {
                HStack(alignment: .bottom, spacing: 2) {
                    ForEach(Array([6,14,18,9,12,5,16].enumerated()), id: \.0) { i, base in
                        WaveBar(baseH: CGFloat(base), delay: Double(i) * 0.12)
                    }
                }.frame(height: 24)
                Text("NutriCam AI scanned your profile")
                    .font(.system(size: 12, weight: .bold))
                    .foregroundColor(Color(red:0.76,green:0.32,blue:0.04))
            }
            VStack(spacing: 8) {
                AICheckItem(status: .done,  label: "Body composition", detail: bmiDetail)
                AICheckItem(status: hasBP ? .done : .warn, label: "Heart health", detail: hasBP ? "BP normal" : "No BP data — add for accuracy")
                AICheckItem(status: hasGlucose ? .done : .warn, label: "Glucose & lipids", detail: hasGlucose ? "Values detected" : "No data — add for accuracy")
                AICheckItem(status: .done, label: "Nutrition targets", detail: "\(report.dailyCalories) kcal/day set")
            }
        }
        .padding(14)
        .background(Color.orange.opacity(0.04)).cornerRadius(16)
        .overlay(RoundedRectangle(cornerRadius: 16).stroke(Color.orange.opacity(0.15), lineWidth: 1))
    }
}

struct WaveBar: View {
    let baseH: CGFloat; let delay: Double
    @State private var phase = false
    var body: some View {
        RoundedRectangle(cornerRadius: 2).fill(Color.orange)
            .frame(width: 3, height: phase ? max(4, baseH * 0.3) : baseH)
            .onAppear {
                DispatchQueue.main.asyncAfter(deadline: .now() + delay) {
                    withAnimation(Animation.easeInOut(duration: 0.9).repeatForever(autoreverses: true)) { phase = true }
                }
            }
    }
}

enum AICheckStatus { case done, warn }
struct AICheckItem: View {
    @EnvironmentObject var themeManager: ThemeManager
    let status: AICheckStatus; let label: String; let detail: String
    var body: some View {
        HStack(spacing: 8) {
            ZStack {
                Circle().fill(status == .done ? Color.green.opacity(0.15) : Color.orange.opacity(0.15)).frame(width: 18, height: 18)
                Image(systemName: status == .done ? "checkmark" : "exclamationmark")
                    .font(.system(size: 8, weight: .bold)).foregroundColor(status == .done ? .green : .orange)
            }
            HStack(spacing: 3) {
                Text(label + " ·").font(.system(size: 12)).foregroundColor(themeManager.current.secondaryText)
                Text(detail).font(.system(size: 12, weight: .semibold))
                    .foregroundColor(status == .warn ? Color(red:0.57,green:0.25,blue:0.0) : themeManager.current.primaryText)
            }
            Spacer()
        }
    }
}

